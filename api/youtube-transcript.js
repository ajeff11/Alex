import {
  extractVideoId,
  fetchPlayerResponse,
  pickSpanishCaptionTrack,
  fetchCaptionSegments,
  getVideoTitle,
  getVideoLengthSeconds,
  listCaptionTracks,
} from './_lib/youtube.js'

export const config = { maxDuration: 30 }

export default async function handler(req, res) {
  if (req.method !== 'GET') {
    res.status(405).json({ error: 'Method not allowed' })
    return
  }

  const url = req.query.url
  if (!url || typeof url !== 'string') {
    res.status(400).json({ error: 'Missing "url" query parameter.' })
    return
  }

  const videoId = extractVideoId(url)
  if (!videoId) {
    res.status(400).json({ error: 'Could not parse a YouTube video ID from that URL.' })
    return
  }

  try {
    const playerResponse = await fetchPlayerResponse(videoId)
    if (!playerResponse) {
      res.status(200).json({ available: false, reason: 'unparseable_page', videoId })
      return
    }

    const status = playerResponse?.playabilityStatus?.status
    if (status && status !== 'OK') {
      res.status(200).json({
        available: false,
        reason: 'not_playable',
        detail: playerResponse?.playabilityStatus?.reason ?? status,
        videoId,
      })
      return
    }

    const title = getVideoTitle(playerResponse)
    const lengthSeconds = getVideoLengthSeconds(playerResponse)
    const track = pickSpanishCaptionTrack(playerResponse)
    if (!track) {
      res.status(200).json({
        available: false,
        reason: 'no_spanish_captions',
        videoId,
        title,
        lengthSeconds,
        captionDiagnostic: listCaptionTracks(playerResponse),
      })
      return
    }

    const segments = await fetchCaptionSegments(track.baseUrl)
    if (segments.length === 0) {
      res.status(200).json({ available: false, reason: 'empty_captions', videoId, title, lengthSeconds })
      return
    }

    res.status(200).json({
      available: true,
      videoId,
      title,
      isAutoGenerated: track.kind === 'asr',
      transcript: segments,
    })
  } catch (err) {
    res.status(200).json({ available: false, reason: 'fetch_error', detail: String(err.message || err), videoId })
  }
}
